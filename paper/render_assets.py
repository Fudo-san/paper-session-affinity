ct=v3['accounting']['ct_library'];g=v3['groups'];sp=v3['specs']
newmacros={'SignP':f"{g['all']['sign']['p_two_sided']:.4f}",
 'NonCTSignP':f"{g['non_ct']['sign']['p_two_sided']:.4f}",
 'ControlCI':interval(g['controls']['ci95']), 'CTCI':interval(sp['ct_library']['ci95']),
 'CTDelta':f"{ct['reported_delta']:.4f}", 'CTStandardDelta':f"{ct['standardized_delta']:.4f}",
 'CTResidualDelta':f"{ct['parts']['residual']['usd_delta']:.4f}",
 'CTWriteShare':f"{100*ct['parts']['cache_creation_tokens']['usd_delta']/ct['standardized_delta']:.1f}",
 'CTReadShare':f"{100*ct['parts']['cache_read_tokens']['usd_delta']/ct['standardized_delta']:.1f}",
 'CTFirstShare':f"{100*v3['ct_tasks']['CT-A']['reported_delta']/ct['reported_delta']:.1f}",
 'CTMeanContribution':f"{100*sp['ct_library']['relative_sum']/98:.2f}",
 'NonCTMeanContribution':f"{100*g['non_ct']['relative_sum']/98:.2f}"}
anc=g['active_non_ct'];cta=v3['ct_tasks']['CT-A']['paired'];mixr=v3['model_mix']['by_reuse']
rr=v3['residual_ratio']['all'];carry={r['task']:r for r in v3['carry_check']['rows']}
