 '\\spec{'+t+'} & '+('あり' if v3['ct_tasks'][t]['activity']['C']['resumed'] else 'なし')+' & '
 +f"${v['paired']['median_turn_delta']:+.1f}$ & {v['context']['B']:,.0f}$\\to${v['context']['C']:,.0f} & "
