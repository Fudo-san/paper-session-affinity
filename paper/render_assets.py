for x,s in zip([0,1,2],['A','B','C']):
 ax.scatter(x,.35,s=1050,color=blue,zorder=3);ax.text(x,.35,s,color='white',ha='center',va='center',weight='bold',fontsize=13)
for a,b in [(0,1),(1,2)]:ax.plot([a,b],[.35,.35],color=gray,lw=3)
ax.text(1,1.15,'Declared write-scope overlap',ha='center',fontsize=10)
ax.text(1,-.35,'A and C do not overlap',ha='center',fontsize=10)
ax.text(1,-.8,'One connected component',ha='center',fontsize=10,color=orange)
ax=axes[1];ax.set_xlim(0,3.2);ax.set_ylim(-.6,3.5)
for y,start,txt,col in [(2.7,0,'Task A',blue),(2.05,0,'Task C',blue),(2.7,1,'Task B',blue),(.45,0,'Task A',orange),(.45,1,'Task B',orange),(.45,2,'Task C',orange)]:
 ax.barh(y,.94,left=start,height=.46,color=col);ax.text(start+.47,y,txt,color='white',ha='center',va='center',fontsize=9)
ax.text(0,3.2,'Policy B: fresh sessions; direct conflicts only',fontsize=9)
ax.text(0,1.13,'Policy C: one continued lane',fontsize=9)
ax.set_yticks([]);ax.set_xticks([0,1,2,3]);ax.set_xlabel('Illustrative time units (not measured)')
ax.spines['left'].set_visible(False);fig.tight_layout();save(fig,'revision_lane_structure')
print('Generated numeric macros, 2 tables, and 4 figures from recorded data.')

# v0.3 post-hoc descriptions, kept distinct from the v0.2 primary results.
