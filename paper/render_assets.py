c=r['corrections']['H1_cost']; q=r['corrections']['H3_quality']; t=r['H2_time']
def interval(values): return '\\ensuremath{['+',\\,'.join(f'{100*x:+.2f}' for x in values)+']}'
def signed(v): return '\\ensuremath{'+v+'}' if v.startswith('-') else v
def macro_lines(d): return ''.join('\\newcommand{\\'+k+'}{'+signed(v)+'}\n' for k,v in d.items())
def minus(s): return re.sub(r'-(?=\d)','\u2212',s)  # sign only; keeps hyphenated words intact
macros=dict(CostMedian=f"{100*c['median_relative_diff']:.2f}",CostP=f"{c['p_value']:.4f}",
 CostCI=interval(c['ci95_relative_diff']),TimeRatio=f"{t['ratio_point']:.4f}",TimeUpper=f"{t['ratio_ci_upper']:.4f}",
 QualityLower=f"{q['ci90_lower_pp']:.2f}",QualityDiff=f"{q['diff_pp']:.2f}",
 QualityExact=f"{r['supplementary']['conservative_exact_quality_lower_pp']:.2f}",
 StratifiedCI=interval(r['supplementary']['fixed_spec_percentile_ci95']),
 TotalB=f"{r['totals']['B']:.2f}",TotalC=f"{r['totals']['C']:.2f}",
 TotalIncrease=f"{100*r['totals']['relative_difference']:.2f}",
 GapSeconds=f"{r['timing']['gap_median']*60:.2f}",GapMax=f"{r['timing']['gap_max']:.2f}")
(out/'numbers.tex').write_text('% Generated by render_assets.py; do not hand-edit.\n'+macro_lines(macros))
rows=r['H4b']['rows']
ordered=sorted(rows,key=lambda v:v['median_relative_diff'])
(out/'spec_rows.tex').write_text('\\begin{tabular}{lrrrr}\n\\toprule 仕様 & B中央値 & C中央値 & 相対差中央値 & Cが安い対\\\\\\midrule\n'+''.join(
 '\\spec{'+v['spec']+'} & '+f"{v['cost_B_median']:.4f} & {v['cost_C_median']:.4f} & ${100*v['median_relative_diff']:+.1f}$\\% & {v['cheaper']}/14 \\\\\n" for v in ordered)+'\\bottomrule\n\\end{tabular}\n')
(out/'model_rows.tex').write_text('\\begin{tabular}{lrrrl}\n\\toprule 仕様 & 実測$r_s$ & 予測$\\widehat r_s$ & 相対誤差 & 25\\%以内\\\\\\midrule\n'+''.join(
 '\\spec{'+v['spec']+'} & '+f"{v['r_observed']:.4f} & {v['r_hat']:.4f} & ${100*v['relative_error']:+.1f}$\\% & "+('はい' if abs(v['relative_error'])<=.25 else 'いいえ')+' \\\\\n' for v in rows)+'\\bottomrule\n\\end{tabular}\n')
plt.rcParams.update({'font.size':10,'axes.spines.top':False,'axes.spines.right':False,'pdf.fonttype':42,'savefig.bbox':'tight'})
blue='#245a83'; orange='#c16a2f'; gray='#6b7280'
def save(fig,name):
 # Omit the PDF CreationDate so a rebuild is byte-identical and can be hashed in a release manifest.
 fig.savefig(figdir/(name+'.pdf'),dpi=180,metadata={'CreationDate':None})
 fig.savefig(figdir/(name+'.png'),dpi=180)
 plt.close(fig)

rel=np.array([100*(p['cost_C']-p['cost_B'])/p['cost_B'] for p in data])
fig,ax=plt.subplots(figsize=(7.2,3.6))
ax.hist(rel,bins=24,color=blue,alpha=.85,edgecolor='white')
ax.axvline(0,color=gray,lw=1)
ax.axvline(np.median(rel),color=orange,ls='--',label=minus(f'Median: {np.median(rel):+.2f}%'))
